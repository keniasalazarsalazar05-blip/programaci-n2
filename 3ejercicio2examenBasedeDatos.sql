-- CREAR TABLA CATEGORIA
CREATE TABLE Categoria (
    Codigo INT PRIMARY KEY AUTO_INCREMENT,
    Nombre VARCHAR(50) NOT NULL
);

-- CREAR TABLA PRODUCTO
CREATE TABLE Producto (
    Codigo INT PRIMARY KEY AUTO_INCREMENT,
    Nombre VARCHAR(50) NOT NULL,
    Precio DECIMAL(10,2),
    Cantidad INT,
    Categoria INT,
    FOREIGN KEY (Categoria) REFERENCES Categoria(Codigo)
);

